#!/usr/bin/env node
// Scans ../assets/source/<group>/*.svg and emits a static manifest at
// web/lib/traitManifest.generated.ts so the trait gallery is fully
// adaptive — adding a new folder or SVG appears in the gallery on next build.

import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..", "..");
const SOURCE_ROOT = join(REPO_ROOT, "assets", "source");
const OUT_PATH = join(__dirname, "..", "lib", "traitManifest.generated.ts");

// Slugs treated as on-chain states, not gainable traits in the gallery.
// Per board:
// - within `skin/`, `base`/`tombstone`/`zombie` are body states
// - within `background/`, `gray` is reserved for the Tombstone state and is
//   never rolled for live tokens (MIN-8 fix in flight).
const STATES_BY_GROUP = {
  skin: new Set(["base", "tombstone", "zombie"]),
  background: new Set(["gray"]),
};

function titleCase(slug) {
  return slug
    .replace(/[_-]+/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .split(" ")
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase())
    .join(" ");
}

function readSvgBody(filePath) {
  const raw = readFileSync(filePath, "utf8").trim();
  // Strip the leading <?xml ?> declaration if any.
  return raw.replace(/^<\?xml[^?]*\?>\s*/, "");
}

function scan() {
  const groups = [];
  const entries = readdirSync(SOURCE_ROOT, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .sort((a, b) => a.name.localeCompare(b.name));

  for (const dir of entries) {
    const groupSlug = dir.name;
    const groupDir = join(SOURCE_ROOT, groupSlug);
    const files = readdirSync(groupDir)
      .filter((f) => f.toLowerCase().endsWith(".svg"))
      .sort((a, b) => a.localeCompare(b));

    const traits = [];
    const states = [];
    for (const file of files) {
      const slug = file.replace(/\.svg$/i, "");
      const svg = readSvgBody(join(groupDir, file));
      const entry = {
        id: `${groupSlug}/${slug}`,
        slug,
        name: titleCase(slug),
        svg,
      };
      const stateSet = STATES_BY_GROUP[groupSlug];
      if (stateSet && stateSet.has(slug.toLowerCase())) {
        states.push(entry);
      } else {
        traits.push(entry);
      }
    }
    groups.push({
      slug: groupSlug,
      name: titleCase(groupSlug),
      traits,
      states,
    });
  }
  return groups;
}

function emit(groups) {
  const banner = `// AUTO-GENERATED by scripts/build-traits.mjs. Do not edit.\n// Regenerate by running \`pnpm --filter web build\` or \`pnpm --filter web prebuild\`.\n// Source: ${relative(REPO_ROOT, SOURCE_ROOT)}/<group>/*.svg\n\n`;
  const body =
    banner +
    `export type TraitEntry = { id: string; slug: string; name: string; svg: string };\n` +
    `export type TraitGroup = {\n` +
    `  slug: string;\n` +
    `  name: string;\n` +
    `  traits: TraitEntry[];\n` +
    `  states: TraitEntry[];\n` +
    `};\n\n` +
    `export const TRAIT_GROUPS: TraitGroup[] = ${JSON.stringify(
      groups,
      null,
      2,
    )};\n`;
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, body, "utf8");
}

try {
  statSync(SOURCE_ROOT);
} catch {
  console.error(`[build-traits] missing source dir: ${SOURCE_ROOT}`);
  process.exit(1);
}

const groups = scan();
emit(groups);
const counts = groups
  .map((g) => `${g.slug}=${g.traits.length}${g.states.length ? `+${g.states.length}st` : ""}`)
  .join(" ");
console.log(`[build-traits] wrote ${relative(REPO_ROOT, OUT_PATH)} (${counts})`);
